// Regenerates lib/pickem-logo-ids.ts from ESPN's public college football
// team list. Run with `node scripts/gen-logo-ids.mjs` when ESPN adds a
// school; the output is keyed by the school name shortTeam() produces so a
// lookup on an Odds API "School Mascot" string lands on the same key.
//
// The endpoint's `groups=` filter is ignored server-side (it returns the
// same first page for FBS and FCS), so fetch everything and keep it all;
// the table is a few hundred lines and never leaves the module scope.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { shortTeam } from "../lib/pickem.ts";

const ENDPOINT = "https://site.api.espn.com/apis/site/v2/sports/football/college-football/teams?limit=1000";

const res = await fetch(ENDPOINT);
if (!res.ok) throw new Error(`ESPN ${res.status}`);
const json = await res.json();
const teams = json.sports[0].leagues[0].teams.map((t) => t.team);

// First id wins per key; ESPN lists the Division I school before any
// same-named small college (e.g. "Miami" is the Hurricanes, id 2390).
const ids = new Map();
for (const t of teams) {
  const key = shortTeam(t.displayName);
  if (!ids.has(key)) ids.set(key, Number(t.id));
}

const rows = [...ids.entries()].sort(([a], [b]) => a.localeCompare(b));
const out = [
  "// Generated by scripts/gen-logo-ids.mjs from ESPN's college football team",
  `// list on ${new Date().toISOString().slice(0, 10)}; ${rows.length} teams. Do not hand-edit: rerun the script.`,
  "// Keys are school names as shortTeam() produces them; values are ESPN team",
  "// ids, which name the logo at a.espncdn.com/i/teamlogos/ncaa/500-dark/{id}.png.",
  "export const ESPN_COLLEGE_IDS: Record<string, number> = {",
  ...rows.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`),
  "};",
  "",
].join("\n");

const target = fileURLToPath(new URL("../lib/pickem-logo-ids.ts", import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${rows.length} teams to lib/pickem-logo-ids.ts`);
