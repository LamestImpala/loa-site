// Regenerates lib/pickem-push-rates.ts: how often a game lands exactly on a
// number, which is what a half point through that number is worth to the
// price engine (lib/pickem-engine.ts).
//
// For each margin n, among games whose closing spread was within 1.5 points
// of n, the share the favourite won by exactly n. Where that is too few
// games (big NFL spreads) the window widens to 3 and then 5 points before
// the margin is given up on. For totals, one flat rate
// per league: the share of games whose final total landed on the closing
// total (rounded half up).
//
// NFL: nflverse games.csv, no key. College: CollegeFootballData /lines, one
// call a season against the free 1,000 a month.
//
//   CFBD_API_KEY=... node scripts/gen-push-rates.mjs [firstSeason] [lastSeason]
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const key = process.env.CFBD_API_KEY;
if (!key) throw new Error("CFBD_API_KEY is not set");
const first = Number(process.argv[2] ?? 2015);
const last = Number(process.argv[3] ?? 2025);

const WINDOWS = [1.5, 3, 5]; // a game counts toward n when its spread is this close to n; widened until MIN_GAMES
const MIN_GAMES = 300; // below this at every window the rate is too noisy to keep; the engine falls back to a flat rate
const MAX_MARGIN = 28;

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};

/** games: { spread: favourite's points (>= 0), fav_margin, total_line, total }[] */
function rates(games) {
  const margin = {};
  for (let n = 0; n <= MAX_MARGIN; n++) {
    const near = WINDOWS.map((w) => games.filter((g) => Math.abs(g.spread - n) <= w)).find((gs) => gs.length >= MIN_GAMES);
    if (!near) continue;
    margin[n] = Math.round((near.filter((g) => g.fav_margin === n).length / near.length) * 10000) / 10000;
  }
  const lined = games.filter((g) => g.total_line != null);
  const total = Math.round((lined.filter((g) => g.total === Math.floor(g.total_line + 0.5)).length / lined.length) * 10000) / 10000;
  return { margin, total, games: games.length };
}

// --- NFL ------------------------------------------------------------------
// spread_line is the home team's margin the line expects (positive: home
// favoured); result is home score less away score.
async function nfl() {
  const res = await fetch("https://github.com/nflverse/nfldata/raw/master/data/games.csv");
  if (!res.ok) throw new Error(`nflverse games.csv ${res.status}`);
  const [head, ...lines] = (await res.text()).trim().split("\n");
  const cols = head.split(",");
  const at = (name) => cols.indexOf(name);
  const [iSeason, iResult, iTotal, iSpread, iTotalLine] = ["season", "result", "total", "spread_line", "total_line"].map(at);
  const out = [];
  for (const line of lines) {
    const f = line.split(",");
    const season = Number(f[iSeason]);
    if (season < first || season > last || f[iResult] === "" || f[iResult] === "NA" || f[iSpread] === "" || f[iSpread] === "NA") continue;
    const spread = Number(f[iSpread]);
    const result = Number(f[iResult]);
    const totalLine = f[iTotalLine] === "" || f[iTotalLine] === "NA" ? null : Number(f[iTotalLine]);
    out.push({ spread: Math.abs(spread), fav_margin: spread >= 0 ? result : -result, total_line: totalLine, total: Number(f[iTotal]) });
  }
  return out;
}

// --- College --------------------------------------------------------------
// /lines gives each game's score and every provider's closing spread (home
// perspective, negative: home favoured) and total; the median stands in for
// the close.
async function college() {
  const out = [];
  for (let year = first; year <= last; year++) {
    const res = await fetch(`https://api.collegefootballdata.com/lines?year=${year}&seasonType=regular`, { headers: { Authorization: `Bearer ${key}` } });
    if (!res.ok) throw new Error(`CFBD /lines ${year} ${res.status}`);
    for (const g of await res.json()) {
      if (g.homeScore == null || g.awayScore == null) continue;
      const spreads = (g.lines ?? []).map((l) => Number(l.spread)).filter((x) => Number.isFinite(x));
      if (!spreads.length) continue;
      const totals = (g.lines ?? []).map((l) => Number(l.overUnder)).filter((x) => Number.isFinite(x) && x > 0);
      const spread = median(spreads);
      const result = g.homeScore - g.awayScore;
      out.push({ spread: Math.abs(spread), fav_margin: spread <= 0 ? result : -result, total_line: totals.length ? median(totals) : null, total: g.homeScore + g.awayScore });
    }
  }
  return out;
}

const [nflGames, collegeGames] = await Promise.all([nfl(), college()]);
const table = { nfl: rates(nflGames), ncaaf: rates(collegeGames) };

const body = `// Generated by scripts/gen-push-rates.mjs from ${first}-${last} results; do not edit by hand.
// margin[n]: among games lined within ${WINDOWS[0]} points of n (wider where
// games are scarce), the share the favourite won by exactly n. total: the share of games landing exactly on
// the closing total. A margin with no entry had too few games; the engine
// falls back to a flat rate there.
import type { League } from "./pickem.ts";

export const PUSH_RATES: Record<League, { margin: Record<number, number>; total: number; games: number }> = ${JSON.stringify(table, null, 2)};
`;
const dest = fileURLToPath(new URL("../lib/pickem-push-rates.ts", import.meta.url));
writeFileSync(dest, body);
console.error(`wrote ${dest}: NFL ${nflGames.length} games, college ${collegeGames.length} games`);
