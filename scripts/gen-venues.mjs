// Regenerates lib/pickem-venues-ncaaf.ts from CollegeFootballData: every FBS
// team's home stadium (from /teams/fbs, keyed by CFBD team id, which is
// ESPN's) and every other venue seating 15,000 or more (from /venues, for
// neutral-site games). Two calls against the free 1,000 a month.
//
//   CFBD_API_KEY=... node scripts/gen-venues.mjs
//
// Venues without coordinates or a time zone are skipped and listed on stderr.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const key = process.env.CFBD_API_KEY;
if (!key) throw new Error("CFBD_API_KEY is not set");
const year = process.argv[2] ?? "2026";

async function cfbd(path) {
  const res = await fetch(`https://api.collegefootballdata.com${path}`, { headers: { Authorization: `Bearer ${key}` } });
  if (!res.ok) throw new Error(`CFBD ${path} ${res.status}`);
  return res.json();
}

// CFBD has served coordinates both as latitude/longitude and as location {x, y}.
function venue(raw, skipped) {
  if (!raw) return null;
  const lat = raw.latitude ?? raw.location?.x;
  const lon = raw.longitude ?? raw.location?.y;
  const tz = raw.timezone;
  if (typeof lat !== "number" || typeof lon !== "number" || !tz) {
    skipped.push(raw.name ?? "?");
    return null;
  }
  return { name: raw.name, lat: Math.round(lat * 10000) / 10000, lon: Math.round(lon * 10000) / 10000, dome: Boolean(raw.dome), tz };
}

const [teams, venues] = await Promise.all([cfbd(`/teams/fbs?year=${year}`), cfbd("/venues")]);
const skipped = [];
const home = {};
for (const t of teams) {
  const v = venue(t.location, skipped);
  if (v) home[String(t.id)] = v;
}
const homeNames = new Set(Object.values(home).map((v) => v.name));
const others = venues
  .filter((r) => (r.capacity ?? 0) >= 15000 && !homeNames.has(r.name))
  .map((r) => venue(r, skipped))
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

const json = (x) => JSON.stringify(x);
const lines = [
  "// Generated by scripts/gen-venues.mjs from CollegeFootballData. Do not edit by",
  "// hand; rerun the script (it needs CFBD_API_KEY, two calls) when a school",
  "// moves stadiums.",
  'import type { Venue } from "./pickem-venues.ts";',
  "",
  "/** Home stadium by CFBD team id, which is ESPN's team id (espnTeamId). */",
  "export const COLLEGE_HOME_VENUES: Record<string, Venue> = {",
  ...Object.entries(home)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([id, v]) => `  ${json(id)}: ${json(v)},`),
  "};",
  "",
  "/** Every other venue seating 15,000 or more, for neutral-site games. */",
  "export const COLLEGE_VENUES: Venue[] = [",
  ...others.map((v) => `  ${json(v)},`),
  "];",
  "",
];
writeFileSync(fileURLToPath(new URL("../lib/pickem-venues-ncaaf.ts", import.meta.url)), lines.join("\n"));
console.log(`${Object.keys(home).length} home stadiums, ${others.length} other venues`);
if (skipped.length) console.error(`skipped without coordinates or time zone: ${skipped.join(", ")}`);
