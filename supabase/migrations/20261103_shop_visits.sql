-- Shop visits: one row per shop page a shopper loads, so the admin's
-- "Interest by day" can count people who browsed without clicking
-- anything. record_events only logs actions (photo opens, Discogs
-- clicks, bundle adds, buy requests), which missed most visitors.
--
-- Same shape of access as record_events: shoppers insert anonymously
-- through /api/track (which validates), only the admin can read.

create table if not exists public.shop_visits (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  path text not null check (char_length(path) between 1 and 200),
  record_id bigint references public.records(id) on delete set null,
  referrer_host text check (char_length(referrer_host) <= 100),
  created_at timestamptz not null default now()
);

comment on table public.shop_visits is
  'Shop page loads by anonymous browser session (localStorage cr_session_id). Powers the visitor bars in the admin''s Interest by day.';
comment on column public.shop_visits.path is
  'Page path under the /records namespace, e.g. /records or /records/r/118-eric-clapton-life-in-12-bars.';
comment on column public.shop_visits.record_id is
  'The record on a record page; null for the catalog.';
comment on column public.shop_visits.referrer_host is
  'Where the session came from (e.g. facebook.com), sent on its first page load only.';

create index if not exists shop_visits_created_at_idx
  on public.shop_visits (created_at desc);

alter table public.shop_visits enable row level security;

drop policy if exists "anon can log visits" on public.shop_visits;
create policy "anon can log visits" on public.shop_visits
  for insert
  with check (true);

drop policy if exists "admin can read visits" on public.shop_visits;
create policy "admin can read visits" on public.shop_visits
  for select
  using ((select auth.jwt() ->> 'email') = 'brandoncgillihan@gmail.com');
