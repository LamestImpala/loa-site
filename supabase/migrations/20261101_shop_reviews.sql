-- Shop reviews: what buyers thought of the shop, shown on the shop home
-- page as a rating and a few quotes.
--
-- Two ways in. A buyer leaves one through a private link
-- (/review/<token>) that is emailed about ten days after their box goes
-- out, or that the admin pastes into a Reddit DM; the link is a
-- review_invites row tied to one paid order, good for one review. The
-- admin also adds reviews left elsewhere (Discogs, eBay, Reddit) by hand.
--
-- Nothing is public until the admin publishes it. Anon can't read or
-- write either table: the review page and the shop home go through the
-- three security-definer functions at the bottom, which expose only the
-- buyer's first name, the published reviews, and the aggregate.

-- ---------------------------------------------------------------------
-- review_invites: one private review link per order.
-- ---------------------------------------------------------------------
create table if not exists public.review_invites (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  token uuid not null unique default gen_random_uuid(),
  email text,
  sent_at timestamptz,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

comment on table public.review_invites is
  'Private review links, one per paid order. Created by the daily review-requests job (emailed) or by "Copy review link" in the admin (pasted into a DM).';
comment on column public.review_invites.email is
  'Where the invite was emailed; null when the link was copied for a DM.';
comment on column public.review_invites.sent_at is
  'When the invite email went out; null for a copied link.';
comment on column public.review_invites.used_at is
  'When the buyer submitted their review. A used link shows a thank-you instead of the form.';

alter table public.review_invites enable row level security;
drop policy if exists "admin full access to review_invites" on public.review_invites;
create policy "admin full access to review_invites" on public.review_invites
  for all
  using ((select auth.jwt() ->> 'email') = 'brandoncgillihan@gmail.com')
  with check ((select auth.jwt() ->> 'email') = 'brandoncgillihan@gmail.com');

-- ---------------------------------------------------------------------
-- shop_reviews: the reviews themselves.
-- ---------------------------------------------------------------------
create table if not exists public.shop_reviews (
  id bigint generated by default as identity primary key,
  order_id bigint unique references public.orders(id) on delete set null,
  source text not null default 'site'
    check (source in ('site', 'discogs', 'ebay', 'reddit', 'other')),
  source_url text,
  reviewer_name text not null check (char_length(reviewer_name) between 1 and 60),
  rating smallint check (rating between 1 and 5),
  body text not null check (char_length(body) between 1 and 1200),
  reviewed_on date not null default current_date,
  status text not null default 'pending'
    check (status in ('pending', 'published', 'hidden')),
  featured boolean not null default false,
  owner_reply text check (char_length(owner_reply) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shop_reviews_status_idx
  on public.shop_reviews (status, featured desc, reviewed_on desc);

comment on column public.shop_reviews.order_id is
  'The order a site review was left for (one review per order). Null for reviews imported from elsewhere.';
comment on column public.shop_reviews.source is
  'site = left through a review link; discogs / ebay / reddit / other = added by the admin from that platform.';
comment on column public.shop_reviews.source_url is
  'Link to the original review on another platform, if there is one.';
comment on column public.shop_reviews.reviewer_name is
  'Name shown with the quote, e.g. "Sam K." or a Reddit handle. The admin can edit it.';
comment on column public.shop_reviews.rating is
  '1-5 stars. Null for imported feedback that had no stars; those show as quotes but are left out of the average.';
comment on column public.shop_reviews.reviewed_on is
  'Date the review was written (the original date for imports).';
comment on column public.shop_reviews.status is
  'pending until the admin publishes or hides it. Only published reviews are public.';
comment on column public.shop_reviews.featured is
  'Featured reviews are quoted on the shop home page first.';
comment on column public.shop_reviews.owner_reply is
  'Optional public reply from the shop, shown beneath the quote.';

alter table public.shop_reviews enable row level security;
drop policy if exists "admin full access to shop_reviews" on public.shop_reviews;
create policy "admin full access to shop_reviews" on public.shop_reviews
  for all
  using ((select auth.jwt() ->> 'email') = 'brandoncgillihan@gmail.com')
  with check ((select auth.jwt() ->> 'email') = 'brandoncgillihan@gmail.com');

-- ---------------------------------------------------------------------
-- review_invite_info(token): what the review page needs to greet the
-- buyer. A first name only — from the PayPal shipping name, or the name an
-- email buyer typed — never the order, address or email.
-- ---------------------------------------------------------------------
create or replace function public.review_invite_info(p_token uuid)
returns table (first_name text, used boolean)
language sql
stable
security definer
set search_path = public
as $$
  select
    nullif(split_part(trim(coalesce(
      o.ship_to ->> 'name',
      case when o.buyer_email is not null then o.buyer_username end,
      '')), ' ', 1), ''),
    i.used_at is not null
  from public.review_invites i
  join public.orders o on o.id = i.order_id
  where i.token = p_token;
$$;

revoke all on function public.review_invite_info(uuid) from public;
grant execute on function public.review_invite_info(uuid) to anon, authenticated;

-- ---------------------------------------------------------------------
-- submit_shop_review(...): the buyer's review, saved as pending.
-- Raises 'invalid link', 'already used', 'invalid review' or
-- 'rate limited'; /api/review maps those to status codes.
-- ---------------------------------------------------------------------
create or replace function public.submit_shop_review(
  p_token uuid, p_rating int, p_body text, p_name text
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  inv public.review_invites%rowtype;
  v_body text := left(trim(coalesce(p_body, '')), 1200);
  v_name text := left(trim(coalesce(p_name, '')), 60);
begin
  -- flood cap: at most 20 site reviews per trailing hour
  if (select count(*) from public.shop_reviews
      where source = 'site' and created_at > now() - interval '1 hour') >= 20 then
    raise exception 'rate limited';
  end if;

  select * into inv from public.review_invites where token = p_token for update;
  if not found then raise exception 'invalid link'; end if;
  if inv.used_at is not null
     or exists (select 1 from public.shop_reviews where order_id = inv.order_id) then
    raise exception 'already used';
  end if;

  if p_rating is null or p_rating not between 1 and 5
     or v_body = '' or v_name = '' then
    raise exception 'invalid review';
  end if;

  insert into public.shop_reviews (order_id, source, reviewer_name, rating, body, status)
  values (inv.order_id, 'site', v_name, p_rating, v_body, 'pending');

  update public.review_invites set used_at = now() where id = inv.id;
end;
$$;

revoke all on function public.submit_shop_review(uuid, int, text, text) from public;
grant execute on function public.submit_shop_review(uuid, int, text, text) to anon, authenticated;

-- ---------------------------------------------------------------------
-- shop_review_summary(): the shop home's rating line and quotes. The
-- average counts only rated reviews; quotes are featured first, then
-- newest, three at most.
-- ---------------------------------------------------------------------
create or replace function public.shop_review_summary()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'count', (select count(*) from public.shop_reviews where status = 'published'),
    'rated_count', (select count(rating) from public.shop_reviews where status = 'published'),
    'average', (select round(avg(rating)::numeric, 1)
                  from public.shop_reviews where status = 'published'),
    'quotes', coalesce((
      select jsonb_agg(q order by q.featured desc, q.reviewed_on desc, q.id desc)
      from (
        select id, reviewer_name, rating, body, source, reviewed_on, owner_reply, featured
        from public.shop_reviews
        where status = 'published'
        order by featured desc, reviewed_on desc, id desc
        limit 3
      ) q
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.shop_review_summary() from public;
grant execute on function public.shop_review_summary() to anon, authenticated;
